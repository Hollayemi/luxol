/**
 * Admin Meat Box catalogue: the categories ("Cow Beef", "Goat" ...) and the
 * options inside them ("Quarter Cow", "Goat Meat by Kg" ...) that customers
 * pick from on the Meat Box page. Staff create, edit and delete both here.
 *
 * Field names mirror the Prisma models MeatBoxCategory and MeatBoxOption, so
 * the weight and price estimates are the flat estimatedMin* / estimatedMax*
 * columns (the customer-side types in meatBox.ts fold them into ranges).
 *
 * Categories and options are read together: one request returns every
 * category with its options nested, because the admin screen shows them side
 * by side. Adjust field names to match the NestJS DTOs.
 */

import type { AdminMeatBoxUnit } from "./adminMeatBox";

/** ActiveStatus in the schema. INACTIVE hides it from customers without deleting it. */
export type AdminMeatBoxActiveStatus = "ACTIVE" | "INACTIVE";

/** MeatBoxOption. Decimals arrive as numbers. */
export type AdminMeatBoxOption = {
  id: string;
  categoryId: string;
  /** "Quarter Cow", "Goat Meat by Kg". Unique. */
  label: string;
  image: string | null;
  /** ANIMAL is priced after weighing, KG is a fixed price per kilo. */
  unit: AdminMeatBoxUnit;
  /** Naira per kg. Only for `unit: "KG"`, null for ANIMAL. */
  pricePerKg: number | null;
  /** Estimated weight of ONE unit, e.g. a quarter cow is 45 - 55 kg. */
  estimatedMinKg: number | null;
  estimatedMaxKg: number | null;
  /** Estimated price of ONE unit, shown to the customer as a range. */
  estimatedMinPrice: number | null;
  estimatedMaxPrice: number | null;
  /** Most the customer can order at once. Null = the backend default. */
  maxQuantity: number | null;
  status: AdminMeatBoxActiveStatus;
  displayOrder: number;
  createdAt: string;
  updatedAt: string;
};

/** MeatBoxCategory, with its options (every status, ordered by displayOrder). */
export type AdminMeatBoxCategory = {
  id: string;
  /** "Cow Beef", "Goat" ... Unique. */
  label: string;
  /** Generated by the backend from the label. */
  slug: string;
  image: string | null;
  status: AdminMeatBoxActiveStatus;
  displayOrder: number;
  createdAt: string;
  updatedAt: string;
  options: AdminMeatBoxOption[];
};

/** Response of GET /admin/meat-box/categories. */
export type AdminMeatBoxCatalogue = {
  items: AdminMeatBoxCategory[];
};

/* ------------------------------------------------------------------ */
/* Categories                                                          */
/* ------------------------------------------------------------------ */

export type CreateAdminMeatBoxCategoryRequest = {
  label: string;
  /** A new image. Omit to keep the current one (or none). */
  image?: File | null;
  status: AdminMeatBoxActiveStatus;
  displayOrder: number;
};

export type UpdateAdminMeatBoxCategoryRequest = Partial<CreateAdminMeatBoxCategoryRequest> & {
  id: string;
};

/* ------------------------------------------------------------------ */
/* Options                                                             */
/* ------------------------------------------------------------------ */

/**
 * Sent as multipart form data (it can carry an image). A field that is
 * `null` is sent as an empty string, which means "clear it": switching an
 * option from KG to ANIMAL clears pricePerKg, and the other way round clears
 * the estimates. The backend should turn empty strings into null.
 */
export type CreateAdminMeatBoxOptionRequest = {
  categoryId: string;
  label: string;
  /** A new image. Omit to keep the current one (or none). */
  image?: File | null;
  unit: AdminMeatBoxUnit;
  pricePerKg?: number | null;
  estimatedMinKg?: number | null;
  estimatedMaxKg?: number | null;
  estimatedMinPrice?: number | null;
  estimatedMaxPrice?: number | null;
  maxQuantity?: number | null;
  status: AdminMeatBoxActiveStatus;
  displayOrder: number;
};

export type UpdateAdminMeatBoxOptionRequest = Partial<CreateAdminMeatBoxOptionRequest> & {
  id: string;
};
