/**
 * Admin Meat Box catalogue: the categories ("Cow Beef", "Goat" ...) and the
 * meat boxes inside them ("Full Goat", "Half Cow", "Quarter Cow" ...) that
 * customers pick from on the Meat Box page. Staff create, edit and delete both
 * here.
 *
 * Pricing lives on the category, weight lives on the box:
 *
 *   box price = category.pricePerKg x option.weightKg
 *   e.g. Goat at ₦8,000/kg, "Full Goat" = 120kg  ->  ₦960,000
 *
 * Staff never type a box price. The backend works it out and returns it as
 * `price`, so changing a category's price per kg re-prices every box in it.
 * Orders keep the price they were placed at.
 *
 * Field names mirror the Prisma models MeatBoxCategory and MeatBoxOption.
 *
 * Categories and options are read together: one request returns every
 * category with its options nested, because the admin screen shows them side
 * by side. Adjust field names to match the NestJS DTOs.
 */

/** ActiveStatus in the schema. INACTIVE hides it from customers without deleting it. */
export type AdminMeatBoxActiveStatus = "ACTIVE" | "INACTIVE";

/** MeatBoxOption. Decimals arrive as numbers. */
export type AdminMeatBoxOption = {
  id: string;
  categoryId: string;
  /** "Full Goat", "Half Cow", "Quarter Cow". Unique. */
  label: string;
  image: string | null;
  /** Weight of ONE box in kg, e.g. a full goat is 120. */
  weightKg: number;
  /** Computed by the backend: the category's `pricePerKg` x `weightKg`. */
  price: number;
  /** Most the customer can order at once. Null = the backend default. */
  maxQuantity: number | null;
  status: AdminMeatBoxActiveStatus;
  displayOrder: number;
  createdAt: string;
  updatedAt: string;
};

/** MeatBoxCategory, with its options (every status, ordered by displayOrder). */
export type AdminMeatBoxCategory = {
  id: string;
  /** "Cow Beef", "Goat" ... Unique. */
  label: string;
  /** Generated by the backend from the label. */
  slug: string;
  image: string | null;
  /** Naira per kg. Every box in the category is priced from this. */
  pricePerKg: number;
  status: AdminMeatBoxActiveStatus;
  displayOrder: number;
  createdAt: string;
  updatedAt: string;
  options: AdminMeatBoxOption[];
};

/** Response of GET /admin/meat-box/categories. */
export type AdminMeatBoxCatalogue = {
  items: AdminMeatBoxCategory[];
};

/* ------------------------------------------------------------------ */
/* Categories                                                          */
/* ------------------------------------------------------------------ */

export type CreateAdminMeatBoxCategoryRequest = {
  label: string;
  /** Naira per kg, e.g. 8000. Required: boxes are priced from it. */
  pricePerKg: number;
  /** A new image. Omit to keep the current one (or none). */
  image?: File | null;
  status: AdminMeatBoxActiveStatus;
  displayOrder: number;
};

export type UpdateAdminMeatBoxCategoryRequest = Partial<CreateAdminMeatBoxCategoryRequest> & {
  id: string;
};

/* ------------------------------------------------------------------ */
/* Options                                                             */
/* ------------------------------------------------------------------ */

/**
 * Sent as multipart form data (it can carry an image). A field that is
 * `null` is sent as an empty string, which means "clear it" (only
 * `maxQuantity` can be cleared). The backend should turn empty strings into
 * null. There is no price field: the backend computes it from the weight.
 */
export type CreateAdminMeatBoxOptionRequest = {
  categoryId: string;
  label: string;
  /** A new image. Omit to keep the current one (or none). */
  image?: File | null;
  /** Weight of ONE box in kg. */
  weightKg: number;
  maxQuantity?: number | null;
  status: AdminMeatBoxActiveStatus;
  displayOrder: number;
};

export type UpdateAdminMeatBoxOptionRequest = Partial<CreateAdminMeatBoxOptionRequest> & {
  id: string;
};
